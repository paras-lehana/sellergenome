def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


class ConversationEngine:
    def __init__(self, settings, store, sarvam) -> None:
        self.settings, self.store, self.sarvam = settings, store, sarvam

    # --- session --------------------------------------------------------------------------------

    def start(self, run: dict, seed_turns: list[dict], operator: bool, opening: bool = False) -> dict:
        persona = run["persona"]
        f = persona["factors"]
        delivery = {
            "language": f.get("language", {}).get("value", "hi-IN"),
            "pace": float(f.get("pace", {}).get("value", 1.0) or 1.0),
            "sentence_length": f.get("sentence_length", {}).get("value", "medium"),
            "warmth": f.get("warmth", {}).get("value", "medium"),
            "empathy": f.get("empathy", {}).get("value", "medium"),
            "formality": f.get("formality", {}).get("value", "respectful"),
            "voice": f.get("voice", {}).get("value", "ritu"),
            "hinglish_mix": f.get("hinglish_mix", {}).get("value", "medium"),
        }
        transcript = []
        for i, t in enumerate(seed_turns[:20]):
            if t.get("who") in ("bot", "seller"):
                transcript.append({"i": len(transcript), "who": t["who"], "text": str(t.get("text", ""))[:600], "gloss": t.get("gloss"),
                                   "scripted": True, "at": utc_now(), "signals": [{"signal": t["signal"], "method": "script"}] if t.get("signal") else []})
        line = ((run.get("teleprompter") or {}).get("opening") or "").strip()
        if opening and not transcript and line:
            # Talk as Seller: the executive (bot) opens with the prepared line; the operator answers as the seller.
            transcript.append({"i": 0, "who": "bot", "text": line[:600], "source": "opening", "at": utc_now(), "signals": [],
                               "delivery": {k: delivery[k] for k in ("language", "pace", "sentence_length", "warmth")}})
        call = {
            "id": "call-" + secrets.token_hex(6), "run_id": run["id"], "seller_id": run["seller_id"], "glid": run["glid"],
            "operator": operator, "created_at": utc_now(), "started_epoch": time.time(),
            "transcript": transcript, "base_delivery": dict(delivery), "delivery": delivery,
            "levels": {k: 0.0 for k in ("frustration", "confusion", "interest", "rush")},
            "switches": [], "stage": next((t.get("stage") for t in reversed(seed_turns) if t.get("stage")), "greeting"),
            "auto_turns": 0, "outcome": None, "meeting_hint": None, "say_next": None, "stopped": False,
            "last_switch_epoch": 0.0, "last_switch_turn": -99,
        }
        self.store.put("calls", call["id"], call)
        return call

    def get(self, call_id: str) -> dict | None:
        return self.store.get("calls", call_id)

    # --- one exchange ---------------------------------------------------------------------------

    async def seller_turn(self, call: dict, run: dict, text: str, source: str) -> dict:
        """Process one seller utterance and generate the bot's reply."""
        if call.get("stopped"):
            raise ValueError("The seller asked to stop — the call has ended.")
        text = text.strip()[:600]
        detected = signals.detect(text, call["delivery"]["language"])
        turn = {"i": len(call["transcript"]), "who": "seller", "text": text, "source": source, "at": utc_now(),
                "signals": detected}
        call["transcript"].append(turn)
        self._update_levels(call, detected)
        applied = self._switch(call, detected, turn["i"])
        if any(d["signal"] == "stop" for d in detected):
            call["stopped"] = True
            call["outcome"] = {"label": "do_not_call", "detail": "Seller asked to stop; call ended immediately and suppressed."}
            reply = "Bilkul, main aapko dobara call nahi karungi. Aapka samay dene ke liye dhanyavaad." if call["delivery"]["language"] != "en-IN" \
                else "Of course, we won't call you again. Thank you for your time."
            call["transcript"].append({"i": len(call["transcript"]), "who": "bot", "text": reply, "at": utc_now(), "policy": "stop"})
            self.store.put("calls", call["id"], call)
            return {"call": call, "applied": applied}
        reply = await self._bot_reply(call, run, applied)
        self.store.put("calls", call["id"], call)
        return {"call": call, "applied": applied, "reply": reply}

    async def auto_turn(self, call: dict, run: dict) -> dict:
        limit = int(self.settings.get("budgets.max_auto_turns_per_call", 24))
        if call["auto_turns"] >= limit:
            raise ValueError(f"Auto conversation paused after {limit} turns — take over to continue.")
        call["auto_turns"] += 1
        text, ms = await self._simulated_seller(call, run)
        result = await self.seller_turn(call, run, text, source="simulated_seller")
        result["seller_ms"] = ms
        return result

    # --- signals and switches -------------------------------------------------------------------

    def _update_levels(self, call: dict, detected: list[dict]) -> None:
        """Exponential recency weighting: each new turn halves older evidence every `turn_half_life` turns."""
        half = float(self.settings.get("persona.turn_half_life", 3))
        decay = math.pow(0.5, 1.0 / max(0.5, half))
        for k in call["levels"]:
            call["levels"][k] = round(call["levels"][k] * decay, 3)
        for d in detected:
            if d["signal"] in call["levels"]:
                call["levels"][d["signal"]] = round(min(1.0, call["levels"][d["signal"]] + d["confidence"]), 3)

    def _switch(self, call: dict, detected: list[dict], turn_index: int) -> list[dict]:
        cooldown_s = float(self.settings.get("persona.cooldown_seconds", 8))
        cooldown_t = int(self.settings.get("persona.cooldown_turns", 1))
        pmin, pmax = self.settings.get("persona.pace_min", 0.8), self.settings.get("persona.pace_max", 1.25)
        now = time.time()
        applied = []
        for d in detected:
            sig = d["signal"]
            if sig in ("stop", "bot_question"):
                entry = {"t_s": round(now - call["started_epoch"], 1), "turn": turn_index, "signal": sig, "cue": d.get("cue"),
                         "method": d["method"], "applied": True, "explicit": True, "changes": {},
                         "reason": "Stop request → end immediately" if sig == "stop" else "Asked if talking to a bot → confirm virtual assistant honestly"}
                call["switches"].append(entry)
                applied.append(entry)
                continue
            changes: dict = {}
            reason = ""
            if sig == "language_switch":
                target = d.get("target_language")
                if target and target != call["delivery"]["language"]:
                    changes["language"] = [call["delivery"]["language"], target]
                    reason = f"Seller moved to {target} → match their language"
            elif sig in signals.RULES:
                rule = signals.RULES[sig]
                reason = rule["reason"]
                if "pace" in rule:
                    new_pace = round(max(pmin, min(pmax, call["delivery"]["pace"] + rule["pace"])), 2)
                    if new_pace != call["delivery"]["pace"]:
                        changes["pace"] = [call["delivery"]["pace"], new_pace]
                for key in ("sentence_length", "warmth", "empathy"):
                    if key in rule and call["delivery"].get(key) != rule[key]:
                        changes[key] = [call["delivery"].get(key), rule[key]]
                for flag in ("simplify", "acknowledge", "advance"):
                    if rule.get(flag):
                        changes[flag] = [False, True]
            if not changes:
                continue
            # Cooldown is per factor: a factor changed moments ago is not flipped again on one ambiguous sentence.
            recent = call.setdefault("factor_changed", {})
            blocked = [k for k in changes if k in recent and (now - recent[k]["epoch"] < cooldown_s or turn_index - recent[k]["turn"] <= cooldown_t)]
            level = call["levels"].get(sig, 0.0)
            repeated = level >= 1.0  # seen again within the recency window → strong enough to override cooldown
            explicit = bool(d.get("explicit"))
            applies = explicit or not blocked or repeated
            entry = {"t_s": round(now - call["started_epoch"], 1), "turn": turn_index, "signal": sig, "cue": d.get("cue"),
                     "method": d["method"], "confidence": d["confidence"], "level": level, "changes": changes, "reason": reason,
                     "explicit": explicit, "applied": applies, "held_by_cooldown": not applies,
                     "override": ("explicit request bypasses cooldown" if explicit and blocked else
                                  f"repeated signal (level {level:.2f}) overrides cooldown" if repeated and blocked else None)}
            if applies:
                for key, (_, new) in changes.items():
                    if key in call["delivery"]:
                        call["delivery"][key] = new
                    recent[key] = {"epoch": now, "turn": turn_index}
                call["last_switch_epoch"], call["last_switch_turn"] = now, turn_index
            call["switches"].append(entry)
            applied.append(entry)
        return applied

    # --- LLM steps ------------------------------------------------------------------------------

    def _scope(self, call: dict) -> str:
        return "operator" if call.get("operator") else "public"

    async def _bot_reply(self, call: dict, run: dict, applied: list[dict]) -> dict:
        seller = run["seller"]
        persona = run["persona"]
        d = call["delivery"]
        tele = run.get("teleprompter") or {}
        flags = {k for s in applied if s.get("applied") for k in s.get("changes", {})}
        wanted = [k for k in ("acknowledge", "simplify", "advance") if k in flags]
        if any(s["signal"] == "bot_question" for s in applied):
            wanted.append("bot_question")
        directives = [prompts.text(f"seller.directive.{k}") for k in wanted]
        # Owner, 2026-10-10: executives' sentences were too long — sellers have little time, so get to the point.
        max_words = 10 if d["sentence_length"] == "short" else 18
        lang_note = {"hi-IN": "romanised Hinglish (Latin script) like 'Ji bilkul, main samajh sakti hoon'", "en-IN": "simple Indian English"}.get(
            d["language"], f"the seller's language ({d['language']}) in its native script")
        contract = run.get("contract") or {}
        plan = (((persona.get("generated") or {}).get("persona") or {}).get("call_plan")) or {}
        fields = contract.get("fields") or {}
        company = (fields.get("company_name") or {}).get("value") if (fields.get("company_name") or {}).get("availability") == "present" else None
        if not company and not str(seller.get("company_name") or "").startswith("Private seller"):
            company = seller.get("company_name")
        demand = teleprompter.value_line(seller, persona, contract, hindi=False)
        facts = {k: v for k, v in {
            "company": company, "products": teleprompter.product_label(seller, persona, contract) or None,
            "city": seller.get("city") or None, "demand_and_last_contact": demand or None,
            "trigger": seller.get("trigger") or None, "call_plan": {"purpose": plan.get("purpose"), "next_step": plan.get("next_step")} if plan else None,
            "summary": persona.get("summary"), "confirm_first": tele.get("confirm_first"),
            "objection_line": (tele.get("objection") or {}).get("line"), "packages": [p["name"] for p in tele.get("packages", [])],
            "locality": (contract.get("locality") or {}).get("locality"),
            # 5.12: competitors, market, payment status, buyers, product line and the reason for the call (live data)
            **(agent_context.call_facts(run) if seller.get("synthetic") is False else agent_context.profile_facts(roster.profile(run["seller_id"]))),
        }.items() if v not in (None, "", [], {})}
        system = prompts.text("seller.bot_turn").format(
            bot_name=self.settings.get("app.bot_name", "Payal"), language=lang_note, max_words=max_words, warmth=d["warmth"],
            empathy=d["empathy"], formality=d["formality"], directives=" ".join(directives))
        history = [{"who": t["who"], "text": t["text"]} for t in call["transcript"][-12:]]
        user = json.dumps({"seller_facts": facts, "conversation": history}, ensure_ascii=False)
        started = time.monotonic()
        try:
            reply = await self.sarvam.chat_json(system, user, scope=self._scope(call), max_tokens=350, temperature=0.4, label="bot-turn")
            data = reply["data"]
            text = str(data.get("reply") or "").strip()[:500] or "Ji, main samajh gayi."
            ms = reply["ms"]
            source = "sarvam"
        except (SarvamError, BudgetExceeded) as error:
            data, ms, source = {}, (time.monotonic() - started) * 1000, f"fallback ({type(error).__name__})"
            text = (tele.get("objection") or {}).get("line") or "Ji, samajh gayi. Kya ek chhoti meeting rakh lein?"
        if data.get("stage") in ("greeting", "qualifying", "package", "meeting", "wrap_up"):
            call["stage"] = data["stage"]
        if isinstance(data.get("meeting"), dict):
            call["meeting_hint"] = data["meeting"]
        if isinstance(data.get("outcome"), dict) and data["outcome"].get("label"):
            call["outcome"] = data["outcome"]
        turn = {"i": len(call["transcript"]), "who": "bot", "text": text, "at": utc_now(), "ms": round(ms, 1), "source": source,
                "delivery": {k: d[k] for k in ("language", "pace", "sentence_length", "warmth")}}
        call["transcript"].append(turn)
        call["say_next"] = {"text": text, "why": [s["reason"] for s in applied if s.get("applied")][:3]}
        return turn

    async def _simulated_seller(self, call: dict, run: dict) -> tuple[str, float]:
        profile = roster.profile(run["seller_id"]) if run["seller_id"].startswith(("syn-", "gen-")) else {}
        archetype = (run.get("persona") or {}).get("archetype") or profile.get("archetype", "curious")
        file = ARCHETYPE_PROMPT.get(archetype, "voice-agent-clean.md")
        base = prompts.text(f"seller.archetype.{ARCHETYPE_FILE_ID[file]}")[:2600]
        seller = run["seller"]
        speaks = profile.get("speaks") or ("Hinglish" if seller.get("language") == "hi-IN" else seller.get("language"))
        note = prompts.text(f"seller.archetype_note.{archetype}") if archetype in ARCHETYPE_NOTE else ""
        system = prompts.text("seller.simulated").format(
            archetype_prompt=base, seller_name=profile.get("contact_name", "Seller"), company=seller.get("company_name"),
            category=seller.get("category"), city=seller.get("city"), speaks=speaks, archetype_note=note,
            concern=(profile.get("last_call") or {}).get("summary", ""))
        history = [{"who": "agent" if t["who"] == "bot" else "you", "text": t["text"]} for t in call["transcript"][-10:]]
        reply = await self.sarvam.chat_json(system, json.dumps({"conversation": history}, ensure_ascii=False),
                                            scope=self._scope(call), max_tokens=200, temperature=0.8, label="sim-seller")
        text = str(reply["data"].get("reply") or "").strip()
        if not text:
            raise ValueError("Simulated seller returned nothing.")
        return text[:400], reply["ms"]
